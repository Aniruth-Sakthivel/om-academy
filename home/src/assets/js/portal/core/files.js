/*
Author       : OM Academy
Description  : Files for the demo. Metadata lives in the "files" collection; uploaded bytes live in IndexedDB
               (never in localStorage). storage: "idb" (uploaded), "asset" (sample file shipped in assets/files/),
               "virtual" (seeded record with no bytes — downloads a generated placeholder text file).
*/

import * as store from "./store.js";
import { nowISO } from "./clock.js";

const DB_NAME = "om-portal-files";
const STORE_NAME = "blobs";
let dbPromise = null;

function openDb() {
  if (!("indexedDB" in window)) return Promise.reject(new Error("IndexedDB unavailable"));
  if (!dbPromise) {
    dbPromise = new Promise((resolve, reject) => {
      const req = indexedDB.open(DB_NAME, 1);
      req.onupgradeneeded = () => req.result.createObjectStore(STORE_NAME);
      req.onsuccess = () => resolve(req.result);
      req.onerror = () => reject(req.error);
    });
  }
  return dbPromise;
}

async function tx(mode, fn) {
  const db = await openDb();
  return new Promise((resolve, reject) => {
    const t = db.transaction(STORE_NAME, mode);
    const result = fn(t.objectStore(STORE_NAME));
    t.oncomplete = () => resolve(result && "result" in result ? result.result : undefined);
    t.onerror = () => reject(t.error);
  });
}

const putBlob = (id, blob) => tx("readwrite", (s) => s.put(blob, id));
const getBlob = (id) => tx("readonly", (s) => s.get(id));
const deleteBlob = (id) => tx("readwrite", (s) => s.delete(id));
export const clearBlobs = () => tx("readwrite", (s) => s.clear()).catch(() => {});

export function downloadBlob(filename, blob) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  a.rel = "noopener";
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 4000);
}

const maxKB = () => (store.get("settings").system || {}).maxUploadKB || 2048;

// Save one uploaded File. Throws when it is over the size limit.
export async function saveUpload(file, { ownerId } = {}) {
  const limit = maxKB();
  if (file.size > limit * 1024) throw new Error(`"${file.name}" is larger than ${Math.round(limit / 1024)} MB.`);
  const id = store.newId("file");
  let storage = "idb";
  try {
    await putBlob(id, file);
  } catch {
    storage = "virtual";
  }
  return store.insert("files", { id, name: file.name, mime: file.type || "application/octet-stream", size: file.size, ownerId: ownerId || null, storage, assetPath: null, uploadedAt: nowISO() });
}

export async function saveUploads(fileList, opts) {
  const out = [];
  for (const f of Array.from(fileList || [])) out.push(await saveUpload(f, opts));
  return out;
}

export async function removeFile(id) {
  store.remove("files", id);
  try {
    await deleteBlob(id);
  } catch {
    /* already gone */
  }
}

function placeholder(rec) {
  return new Blob(
    [
      `OM Academy — demo file\n\nFile: ${rec.name}\n\nThis is a placeholder generated by the portal demo. ` +
        `In the live system this download returns the original file that was uploaded.\n`,
    ],
    { type: "text/plain" }
  );
}

export async function getFileBlob(idOrRecord) {
  const rec = typeof idOrRecord === "string" ? store.byId("files", idOrRecord) : idOrRecord;
  if (!rec) throw new Error("File not found.");
  if (rec.storage === "asset" && rec.assetPath) {
    const res = await fetch(rec.assetPath);
    if (!res.ok) throw new Error("Could not load " + rec.name);
    return res.blob();
  }
  if (rec.storage === "idb") {
    try {
      const blob = await getBlob(rec.id);
      if (blob) return blob;
    } catch {
      /* fall through to placeholder */
    }
  }
  return placeholder(rec);
}

// Name used when the stored bytes are a placeholder text file
const downloadName = (rec, blob) => (blob.type === "text/plain" && !/\.txt$/i.test(rec.name) && rec.storage !== "asset" && rec.storage !== "idb" ? rec.name + ".txt" : rec.name);

export async function downloadFile(idOrRecord) {
  const rec = typeof idOrRecord === "string" ? store.byId("files", idOrRecord) : idOrRecord;
  const blob = await getFileBlob(rec);
  downloadBlob(downloadName(rec, blob), blob);
}

const urlCache = new Map();

// Object URL for previews (images, PDFs). Cached per file id.
export async function objectUrl(id) {
  if (!id) return null;
  if (urlCache.has(id)) return urlCache.get(id);
  const rec = store.byId("files", id);
  if (!rec) return null;
  if (rec.storage === "asset") return rec.assetPath;
  const blob = await getFileBlob(rec);
  const url = URL.createObjectURL(blob);
  urlCache.set(id, url);
  return url;
}

// Fill <img data-file-src="fileId"> elements under root with their object URLs
export async function hydrateImages(root = document) {
  const imgs = root.querySelectorAll("img[data-file-src]");
  for (const img of imgs) {
    const url = await objectUrl(img.getAttribute("data-file-src")).catch(() => null);
    if (url) img.src = url;
  }
}

// Square-crop and resize an image File to a JPEG Blob (profile photos)
export function resizeImage(file, size = 160) {
  return new Promise((resolve, reject) => {
    const img = new Image();
    const url = URL.createObjectURL(file);
    img.onload = () => {
      const s = Math.min(img.naturalWidth, img.naturalHeight);
      const canvas = document.createElement("canvas");
      canvas.width = size;
      canvas.height = size;
      canvas.getContext("2d").drawImage(img, (img.naturalWidth - s) / 2, (img.naturalHeight - s) / 2, s, s, 0, 0, size, size);
      URL.revokeObjectURL(url);
      canvas.toBlob((blob) => (blob ? resolve(blob) : reject(new Error("Could not process the image."))), "image/jpeg", 0.85);
    };
    img.onerror = () => {
      URL.revokeObjectURL(url);
      reject(new Error("That file is not an image."));
    };
    img.src = url;
  });
}

// Save a resized profile photo; returns the file record
export async function savePhoto(file, ownerId) {
  const blob = await resizeImage(file);
  const photo = new File([blob], "profile-photo.jpg", { type: "image/jpeg" });
  return saveUpload(photo, { ownerId });
}

// Export uploaded bytes as base64 (Settings → Data → export with files)
export async function exportBlobs() {
  const out = {};
  for (const rec of store.get("files").filter((f) => f.storage === "idb")) {
    try {
      const blob = await getBlob(rec.id);
      if (!blob) continue;
      out[rec.id] = await new Promise((resolve) => {
        const r = new FileReader();
        r.onload = () => resolve(r.result);
        r.readAsDataURL(blob);
      });
    } catch {
      /* skip unreadable */
    }
  }
  return out;
}

export async function importBlobs(map = {}) {
  for (const [id, dataUrl] of Object.entries(map)) {
    try {
      const blob = await (await fetch(dataUrl)).blob();
      await putBlob(id, blob);
    } catch {
      /* skip */
    }
  }
}
